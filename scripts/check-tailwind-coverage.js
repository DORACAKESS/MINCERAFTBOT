'use strict';

/* Coverage check: every Tailwind class used in the dashboard's own HTML/JS
   must exist in the compiled public/css/tailwind.css (custom classes live in
   style.css and are checked against that too). Prints missing classes.
   The minified 3D-viewer bundle (public/viewer/index.js) is skipped — it is
   generated by prismarine-viewer and never uses these utility classes. */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');

const tailwind = fs.readFileSync(path.join(PUBLIC, 'css', 'tailwind.css'), 'utf8');
const style = fs.readFileSync(path.join(PUBLIC, 'css', 'style.css'), 'utf8');

const SKIP = new Set(['index.js']); // minified viewer bundle

function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(html|js)$/.test(e.name) && !SKIP.has(e.name)) out.push(p);
  }
}
const files = [];
walk(PUBLIC, files);

const CLASS_TOKEN = /^[a-zA-Z][a-zA-Z0-9:._\[\]\/\\#%-]*$/;
const PLAIN_UTILS = new Set([
  'hidden', 'flex', 'grid', 'block', 'inline', 'inline-block', 'absolute', 'fixed',
  'relative', 'sticky', 'static', 'none', 'auto', 'left', 'right', 'top', 'bottom',
  'center', 'middle', 'start', 'end', 'wrap', 'nowrap', 'column', 'row', 'pointer',
  'select-none', 'truncate', 'antialiased', 'shrink-0', 'grow', 'visible', 'invisible',
  'opacity-0', 'opacity-100', 'z-10', 'z-20', 'z-30', 'z-40', 'z-50'
]);

const tokens = new Set();
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  // HTML class attributes — the authoritative source.
  for (const m of src.matchAll(/class="([^"]*)"/g)) {
    for (const t of m[1].split(/\s+/)) {
      if (t && CLASS_TOKEN.test(t) && t.length >= 2) tokens.add(t);
    }
  }
  // JS files (not minified bundles): only literal class-NAME fragments used
  // in className assignments / template literals — e.g. the 'badge' in
  // `'badge ' + cls`. Matches short quoted strings of 2-4 words separated by
  // spaces that are entirely class-name characters (skip socket events,
  // model names and ids by requiring a space or a known class keyword).
  if (f.endsWith('.js')) {
    for (const m of src.matchAll(/[`'"]((?:[a-zA-Z][a-zA-Z0-9:_\[\]\/.#%-]*\s+){1,3}[a-zA-Z][a-zA-Z0-9:_\[\]\/.#%-]*)[`'"]/g)) {
      for (const t of m[1].split(/\s+/)) {
        if (!t || t.length < 2) continue;
        if (CLASS_TOKEN.test(t) && (t.includes('-') || t.includes(':') || t.includes('[') || PLAIN_UTILS.has(t))) {
          tokens.add(t);
        }
      }
    }
  }
}

function cssEscape(cls) {
  return cls.replace(/[\\:[\]/.#%'"(),!]/g, (c) => '\\' + c);
}

const missing = [];
for (const cls of [...tokens].sort()) {
  const esc = cssEscape(cls);
  if (!tailwind.includes(esc) && !style.includes(cls)) missing.push(cls);
}

console.log('scanned files:', files.length, '| unique classes:', tokens.size);
if (missing.length) {
  console.log('MISSING (' + missing.length + '):');
  console.log('  ' + missing.join('  '));
} else {
  console.log('COVERAGE OK — every class is in tailwind.css or style.css');
}
